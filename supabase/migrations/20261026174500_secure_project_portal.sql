-- Secure single-project portal schema for four separately hosted React origins.
-- Apply with Supabase migrations. Configure Auth redirect URLs for each origin in Dashboard.
-- Account creation and password issuance are trusted server-only operations; never store passwords here.
-- After applying this migration, create the first admin with scripts/create-admin.mjs.
-- It uses the Auth Admin API, generates a one-time password, and creates the matching profile.
-- Do not create an open bootstrap function or permit public signup to assign privileged roles.
-- Run once on the intended Supabase project. All DDL is transactional; same-named objects cause
-- an error and rollback instead of being dropped or overwritten.

begin;

create extension if not exists pgcrypto with schema extensions;

create type public.app_role as enum ('admin', 'client', 'worker');
create type public.document_audience as enum ('admin_only', 'workers', 'client');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role public.app_role not null,
  username text not null,
  username_normalized text generated always as (lower(btrim(username))) stored,
  full_name text not null,
  enabled boolean not null default true,
  password_change_required boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_username_nonempty check (username_normalized <> ''),
  constraint profiles_username_format check (username_normalized ~ '^[a-z0-9][a-z0-9._-]{1,62}$'),
  constraint profiles_username_unique unique (username_normalized)
);

-- Keep first-use credential fingerprints out of exposed public tables. Passwords themselves
-- are never stored here; generated passwords use high-entropy random bytes and are returned once.
-- The public-schema table has no anon/authenticated privileges or RLS policies; only the trusted
-- service role can query it. A unique fingerprint prevents accidental initial-password reuse.
create table public.issued_credential_fingerprints (
  fingerprint text primary key check (fingerprint ~ '^[0-9a-f]{64}$'),
  profile_id uuid not null unique references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now()
);
revoke all on table public.issued_credential_fingerprints from public, anon, authenticated;
grant select, insert on table public.issued_credential_fingerprints to service_role;
alter table public.issued_credential_fingerprints enable row level security;

create table public.worker_titles (
  id bigint generated by default as identity primary key,
  title text not null,
  title_normalized text generated always as (lower(btrim(title))) stored,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  constraint worker_titles_title_nonempty check (title_normalized <> ''),
  constraint worker_titles_title_unique unique (title_normalized)
);
create table public.worker_title_assignments (
  worker_id uuid primary key references public.profiles(id) on delete cascade,
  title_id bigint not null references public.worker_titles(id) on delete restrict,
  assigned_at timestamptz not null default now()
);

create table public.projects (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  description text,
  status text not null default 'active' check (status in ('draft','active','completed','archived')),
  published boolean not null default false,
  published_at timestamptz,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table public.project_clients (
  project_id uuid not null references public.projects(id) on delete cascade,
  client_id uuid not null references public.profiles(id) on delete cascade,
  assigned_at timestamptz not null default now(),
  primary key (project_id, client_id)
);
create table public.project_workers (
  project_id uuid not null references public.projects(id) on delete cascade,
  worker_id uuid not null references public.profiles(id) on delete cascade,
  assigned_at timestamptz not null default now(),
  primary key (project_id, worker_id)
);

create table public.project_updates (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects(id) on delete cascade,
  title text not null,
  body text not null,
  published boolean not null default false,
  published_at timestamptz,
  author_id uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table public.internal_messages (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete restrict,
  recipient_id uuid references public.profiles(id) on delete set null,
  body text not null,
  created_at timestamptz not null default now()
);
create table public.progress_reports (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects(id) on delete cascade,
  worker_id uuid not null references public.profiles(id) on delete restrict,
  body text not null,
  created_at timestamptz not null default now()
);
create table public.project_documents (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects(id) on delete cascade,
  storage_path text not null unique,
  file_name text not null,
  audience public.document_audience not null,
  uploaded_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  constraint project_documents_path_nonempty check (storage_path <> '')
);

-- Import audit records intentionally exclude passwords and other authentication secrets.
create table public.worker_import_batches (
  id uuid primary key default gen_random_uuid(),
  created_by uuid not null references public.profiles(id) on delete restrict,
  created_count integer not null default 0 check (created_count >= 0),
  failed_count integer not null default 0 check (failed_count >= 0),
  created_at timestamptz not null default now()
);
create table public.worker_import_entries (
  id uuid primary key default gen_random_uuid(),
  batch_id uuid not null references public.worker_import_batches(id) on delete cascade,
  full_name text not null,
  username text,
  profile_id uuid references public.profiles(id) on delete set null,
  outcome text not null check (outcome in ('created','failed')),
  created_at timestamptz not null default now()
);

create index profiles_role_enabled_idx on public.profiles(role, enabled);
create index project_clients_client_idx on public.project_clients(client_id, project_id);
create index project_workers_worker_idx on public.project_workers(worker_id, project_id);
create index projects_published_idx on public.projects(published, published_at desc);
create index project_updates_project_published_idx on public.project_updates(project_id, published, published_at desc);
create index internal_messages_project_created_idx on public.internal_messages(project_id, created_at);
create index progress_reports_project_created_idx on public.progress_reports(project_id, created_at);
create index project_documents_project_audience_idx on public.project_documents(project_id, audience);
create index worker_import_entries_batch_idx on public.worker_import_entries(batch_id, created_at);

create function public.touch_updated_at()
returns trigger language plpgsql set search_path = pg_catalog, public
as $$ begin new.updated_at = now(); return new; end $$;
create trigger profiles_touch_updated_at before update on public.profiles
for each row execute function public.touch_updated_at();
create trigger projects_touch_updated_at before update on public.projects
for each row execute function public.touch_updated_at();
create trigger project_updates_touch_updated_at before update on public.project_updates
for each row execute function public.touch_updated_at();
revoke all on function public.touch_updated_at() from public, anon, authenticated;

-- SECURITY DEFINER membership predicates avoid recursive RLS lookups. Fixed search_path and
-- explicit row ownership checks; execute only for authenticated callers (and postgres owner).
create function public.current_enabled_role()
returns public.app_role language sql stable security definer
set search_path = pg_catalog, public, auth
as $$ select p.role from public.profiles p where p.id = (select auth.uid()) and p.enabled $$;
create function public.is_admin()
returns boolean language sql stable security definer
set search_path = pg_catalog, public, auth
as $$ select coalesce(public.current_enabled_role() = 'admin'::public.app_role, false) $$;
create function public.is_client_on_project(p_project uuid)
returns boolean language sql stable security definer
set search_path = pg_catalog, public, auth
as $$ select exists (select 1 from public.project_clients pc join public.profiles p on p.id=pc.client_id where pc.project_id=p_project and pc.client_id=(select auth.uid()) and p.enabled and p.role='client') $$;
create function public.is_worker_on_project(p_project uuid)
returns boolean language sql stable security definer
set search_path = pg_catalog, public, auth
as $$ select exists (select 1 from public.project_workers pw join public.profiles p on p.id=pw.worker_id where pw.project_id=p_project and pw.worker_id=(select auth.uid()) and p.enabled and p.role='worker') $$;
revoke all on function public.current_enabled_role() from public, anon;
revoke all on function public.is_admin() from public, anon;
revoke all on function public.is_client_on_project(uuid) from public, anon;
revoke all on function public.is_worker_on_project(uuid) from public, anon;
grant execute on function public.current_enabled_role(), public.is_admin(), public.is_client_on_project(uuid), public.is_worker_on_project(uuid) to authenticated;

-- Exposed tables have RLS enabled and no anon access. Admin client operations remain explicit;
-- account creation/password generation must be performed by a trusted server using Auth Admin API.
revoke all on table public.profiles, public.issued_credential_fingerprints, public.worker_titles,
 public.worker_title_assignments, public.projects, public.project_clients, public.project_workers,
 public.project_updates, public.internal_messages, public.progress_reports, public.project_documents,
 public.worker_import_batches, public.worker_import_entries from anon, authenticated;
revoke all on sequence public.worker_titles_id_seq from anon, authenticated;
grant usage on schema public to authenticated;
-- The public portfolio is static; private client projects are never readable through anon REST.
grant select, insert, update, delete on public.profiles, public.worker_titles, public.worker_title_assignments,
 public.projects, public.project_clients, public.project_workers, public.project_updates,
 public.internal_messages, public.progress_reports, public.project_documents,
 public.worker_import_batches, public.worker_import_entries to authenticated;
grant usage on schema public to service_role;
grant all privileges on table public.profiles, public.issued_credential_fingerprints, public.worker_titles,
 public.worker_title_assignments, public.projects, public.project_clients, public.project_workers,
 public.project_updates, public.internal_messages, public.progress_reports, public.project_documents,
 public.worker_import_batches, public.worker_import_entries to service_role;
grant usage, select on sequence public.worker_titles_id_seq to service_role;

alter table public.profiles enable row level security;
alter table public.worker_titles enable row level security;
alter table public.worker_title_assignments enable row level security;
alter table public.projects enable row level security;
alter table public.project_clients enable row level security;
alter table public.project_workers enable row level security;
alter table public.project_updates enable row level security;
alter table public.internal_messages enable row level security;
alter table public.progress_reports enable row level security;
alter table public.project_documents enable row level security;
alter table public.worker_import_batches enable row level security;
alter table public.worker_import_entries enable row level security;

create policy profiles_read_self_admin on public.profiles for select to authenticated using (id=(select auth.uid()) or (select public.is_admin()));
create policy profiles_admin_insert on public.profiles for insert to authenticated with check ((select public.is_admin()));
create policy profiles_admin_update on public.profiles for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy profiles_admin_delete on public.profiles for delete to authenticated using ((select public.is_admin()));
create policy worker_titles_admin_all on public.worker_titles for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy worker_title_assignments_admin_all on public.worker_title_assignments for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

create policy projects_admin_all on public.projects for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy projects_client_read on public.projects for select to authenticated using (published and (select public.is_client_on_project(id)));
create policy projects_worker_read on public.projects for select to authenticated using ((select public.is_worker_on_project(id)));
create policy project_clients_admin_all on public.project_clients for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy project_clients_client_read_self on public.project_clients for select to authenticated using (client_id=(select auth.uid()) and (select public.current_enabled_role())='client');
create policy project_workers_admin_all on public.project_workers for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy project_workers_worker_read_self on public.project_workers for select to authenticated using (worker_id=(select auth.uid()) and (select public.current_enabled_role())='worker');

create policy updates_admin_all on public.project_updates for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy updates_client_read_published on public.project_updates for select to authenticated using (published and (select public.is_client_on_project(project_id)));
-- Workers may not create or publish client-facing updates.
create policy internal_messages_admin_all on public.internal_messages for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy internal_messages_worker_read_own_assigned on public.internal_messages for select to authenticated using (
 (sender_id=(select auth.uid()) or recipient_id=(select auth.uid())) and (select public.is_worker_on_project(project_id))
);
create policy internal_messages_worker_insert_assigned on public.internal_messages for insert to authenticated with check (
 sender_id=(select auth.uid()) and recipient_id is null and (select public.is_worker_on_project(project_id))
);
create policy progress_reports_admin_all on public.progress_reports for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy progress_reports_worker_read_own on public.progress_reports for select to authenticated using (
 worker_id=(select auth.uid()) and (select public.is_worker_on_project(project_id))
);
create policy progress_reports_worker_insert_self on public.progress_reports for insert to authenticated with check (worker_id=(select auth.uid()) and (select public.is_worker_on_project(project_id)));

create policy documents_admin_all on public.project_documents for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy documents_worker_read_shared on public.project_documents for select to authenticated using ((select public.is_worker_on_project(project_id)) and audience='workers');
create policy documents_client_read_shared on public.project_documents for select to authenticated using (audience='client' and (select public.is_client_on_project(project_id)));
create policy worker_import_batches_admin_all on public.worker_import_batches for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy worker_import_entries_admin_all on public.worker_import_entries for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

-- Private, Obragoito-specific bucket only. Paths are opaque; metadata is authoritative for project and audience.
insert into storage.buckets (id, name, public) values ('obragoito-private-project-documents','obragoito-private-project-documents',false)
on conflict (id) do update set public=false;
create policy project_storage_admin_all on storage.objects for all to authenticated
 using (bucket_id='obragoito-private-project-documents' and (select public.is_admin()))
 with check (bucket_id='obragoito-private-project-documents' and (select public.is_admin()));
create policy project_storage_worker_read on storage.objects for select to authenticated using (
 bucket_id='obragoito-private-project-documents' and exists (
  select 1 from public.project_documents d where d.storage_path=name and d.audience in ('workers','admin_only') and (select public.is_worker_on_project(d.project_id))
 ));
create policy project_storage_client_read on storage.objects for select to authenticated using (
 bucket_id='obragoito-private-project-documents' and exists (
  select 1 from public.project_documents d where d.storage_path=name and d.audience='client' and (select public.is_client_on_project(d.project_id))
 ));

comment on table public.project_updates is 'Client-visible content: only admin can insert/edit/publish; clients read published updates for assigned projects.';
comment on table public.internal_messages is 'Internal worker/admin communication. Never expose to client sessions.';
comment on table public.progress_reports is 'Internal worker progress reports. Never expose to client sessions.';
comment on table public.project_documents is 'Storage metadata is the authorization source; upload metadata/admin provisioning should be performed in a trusted application flow.';
comment on policy project_storage_admin_all on storage.objects is 'Only enabled admins can manage this private bucket. Worker/client uploads are not enabled by policy.';

commit;
